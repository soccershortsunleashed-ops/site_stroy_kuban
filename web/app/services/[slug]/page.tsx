export function generateStaticParams() {
  return services.map((service) => ({ slug: service.slug }))
}

export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { slug } = await params
  const service = services.find((item) => item.slug === slug)

  if (!service) {
    return {
      title: "Услуга не найдена",
      robots: { index: false, follow: false },
    }
  }

  const seo = serviceSeoContent[service.slug]
  const commercialTitle = seo?.title ?? `${service.title} в Краснодаре, Сочи и Сириусе`
  const commercialDescription =
    seo?.description ??
    `${service.description} Работаем по Краснодару, Сочи и федеральной территории Сириус.`

  return {
    title: commercialTitle,
    description: commercialDescription,
    keywords: [
      service.title,
      ...(seo?.keywords ?? []),
      ...service.tags,
      "услуги строительной компании",
      "СтройТрест-23",
    ],
    alternates: {
      canonical: `/services/${service.slug}`,
    },
    openGraph: {
      title: `${commercialTitle} | СтройТрест-23`,
      description: commercialDescription,
      url: `/services/${service.slug}`,
      type: "article",
    },
  }
}

